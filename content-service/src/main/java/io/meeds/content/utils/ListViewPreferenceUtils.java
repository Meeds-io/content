package io.meeds.content.utils;

import java.util.ArrayList;
import java.util.List;
import java.util.function.Predicate;
import java.util.stream.StreamSupport;

import org.apache.commons.collections4.MapUtils;
import org.apache.commons.lang3.StringUtils;

import org.exoplatform.portal.pom.spi.portlet.Portlet;
import org.exoplatform.portal.pom.spi.portlet.Preference;

import io.meeds.layout.model.PortletInstanceContext;
import io.meeds.layout.model.PortletInstancePreference;
import io.meeds.social.translation.model.TranslationField;
import io.meeds.social.translation.service.TranslationService;
import io.meeds.social.util.JsonUtils;

import lombok.SneakyThrows;

/**
 * Builds the preferences of a copied News List or Content List instance
 */
public class ListViewPreferenceUtils {

  public static final String APPLICATION_ID_PREFERENCE_NAME = "applicationId";

  public static final String DATA_INIT_PREFERENCE_NAME      = "data.init";

  public static final String CMS_SETTING_PREFERENCE_NAME    = "name";

  private ListViewPreferenceUtils() {
    // Utility class
  }

  /**
   * Copies the display settings of the instance, then adds its header title as
   * the {@code data.init} payload, read from the translation field keyed by the
   * instance application id. Without an application id, the {@code data.init}
   * preference of the instance is kept as is.
   *
   * @param preferences the preferences of the copied instance
   * @param portletInstanceContext the copy context
   * @param translationService the service holding the header title
   * @param headerObjectType the header title translation object type
   * @param headerFieldName the header title translation field name
   * @param exportExcluded matches the preferences left out of an export: the
   *          ids of the exporting platform, and the settings that only work
   *          with them
   * @return the preferences of the copy
   */
  @SneakyThrows
  public static List<PortletInstancePreference> generatePreferences(Portlet preferences,
                                                                    PortletInstanceContext portletInstanceContext,
                                                                    TranslationService translationService,
                                                                    String headerObjectType,
                                                                    String headerFieldName,
                                                                    Predicate<Preference> exportExcluded) {
    List<PortletInstancePreference> result = copyPreferences(preferences, portletInstanceContext, exportExcluded);
    String applicationId = getPreferenceValue(preferences, APPLICATION_ID_PREFERENCE_NAME);
    if (StringUtils.isBlank(applicationId)) {
      String dataInit = getPreferenceValue(preferences, DATA_INIT_PREFERENCE_NAME);
      if (dataInit != null) {
        result.add(new PortletInstancePreference(DATA_INIT_PREFERENCE_NAME, dataInit));
      }
      return result;
    }
    TranslationField translationField = translationService.getTranslationField(headerObjectType,
                                                                               applicationId,
                                                                               headerFieldName);
    if (MapUtils.isNotEmpty(translationField.getLabels())) {
      result.add(new PortletInstancePreference(DATA_INIT_PREFERENCE_NAME, JsonUtils.toJsonString(translationField)));
    }
    return result;
  }

  /**
   * Copies the display settings of the instance, but not the preferences that
   * identify it: the CMS setting name, the application id keying its header
   * title translation, and the header title payload, regenerated by the caller.
   * An export also leaves out the preferences matched by the given predicate
   */
  private static List<PortletInstancePreference> copyPreferences(Portlet preferences,
                                                                 PortletInstanceContext portletInstanceContext,
                                                                 Predicate<Preference> exportExcluded) {
    boolean export = portletInstanceContext != null && portletInstanceContext.isExport();
    List<PortletInstancePreference> result = new ArrayList<>();
    if (preferences != null) {
      StreamSupport.stream(preferences.spliterator(), false)
                   .filter(preference -> !StringUtils.equalsAny(preference.getName(),
                                                                CMS_SETTING_PREFERENCE_NAME,
                                                                APPLICATION_ID_PREFERENCE_NAME,
                                                                DATA_INIT_PREFERENCE_NAME))
                   .filter(preference -> !export || !exportExcluded.test(preference))
                   .forEach(preference -> result.add(new PortletInstancePreference(preference.getName(),
                                                                                   preference.getValue())));
    }
    return result;
  }

  private static String getPreferenceValue(Portlet preferences, String name) {
    if (preferences == null) {
      return null;
    }
    Preference preference = preferences.getPreference(name);
    return preference == null ? null : preference.getValue();
  }

}
